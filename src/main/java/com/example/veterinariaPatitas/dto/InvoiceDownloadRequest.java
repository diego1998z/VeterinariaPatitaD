package com.example.veterinariaPatitas.dto;

import java.util.ArrayList;
import java.util.List;

public class InvoiceDownloadRequest {

    private List<InvoiceItemRequest> items = new ArrayList<>();
    private Double subtotal;
    private Double tax;
    private Double total;
    private String username;

    public List<InvoiceItemRequest> getItems() {
        return items;
    }

    public void setItems(List<InvoiceItemRequest> items) {
        this.items = items;
    }

    public Double getSubtotal() {
        return subtotal;
    }

    public void setSubtotal(Double subtotal) {
        this.subtotal = subtotal;
    }

    public Double getTax() {
        return tax;
    }

    public void setTax(Double tax) {
        this.tax = tax;
    }

    public Double getTotal() {
        return total;
    }

    public void setTotal(Double total) {
        this.total = total;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }
}
